#!/usr/bin/env python3
"""Turn a tb_hier VCD into a TikZ timing figure of the modified-Harvard system.

Like tools/vcd2tikz.py (whose VCD reader it reuses), the figure is generated
from the real simulation: one column per clock cycle, sampled at the falling
edge. It shows the core's two ports, their ready signals, and who owns the
shared lower-level memory in each cycle, so I-cache misses, D-cache misses,
write-buffer drains and cycles with a simultaneous fetch and data access are
all visible.

Usage (from sim/, after 'make figure-hier' has produced the VCD):
    python3 ../tools/vcd2tikz_hier.py build/tb_hier_memcopy.vcd \
        -o ../report/figures/wave_hier.tex --first 8 --cycles 20
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from vcd2tikz import parse_vcd, value_at, to_int  # noqa: E402

P = "tb_hier.mh."
SIG = {
    "clk": "tb_hier.clk", "rst": "tb_hier.rst",
    "pc": P + "i_addr", "i_ready": P + "i_ready",
    "d_addr": P + "d_addr", "d_re": P + "d_re", "d_we": P + "d_we", "d_ready": P + "d_ready",
    "m_req": P + "m_req", "m_we": P + "m_we", "sel_d": P + "u_arb.sel_d", "m_addr": P + "m_addr",
    "m_ready": P + "m_ready", "wb_valid": P + "u_dcache.wb_valid",
}
ROWS = [("i\\_addr (PC)", "pc"), ("i\\_ready", "i_ready"), ("d\\_addr", "d_addr"),
        ("d\\_ready", "d_ready"), ("memory", "owner"), ("m\\_addr", "m_addr"),
        ("wbuf valid", "wb_valid")]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("vcd")
    ap.add_argument("-o", "--out", required=True)
    ap.add_argument("--cycles", type=int, default=20)
    ap.add_argument("--first", type=int, default=8)
    a = ap.parse_args()

    ch = parse_vcd(a.vcd, set(SIG.values()))
    rst_low = next(t for t, v in ch[SIG["rst"]] if v == "0")
    falls = [t for t, v in ch[SIG["clk"]] if v == "0" and t >= rst_low]
    samples = falls[a.first:a.first + a.cycles]
    s = {k: [to_int(value_at(ch[p], t)) for t in samples] for k, p in SIG.items()}

    W, H, LBL = 0.86, 0.55, -0.2
    n = len(samples)
    out = ["% generated by tools/vcd2tikz_hier.py from " + os.path.basename(a.vcd) + " -- do not edit",
           "\\begin{tikzpicture}[font=\\scriptsize\\ttfamily, x=1cm, y=1cm]"]
    for i in range(n):
        out.append(f"\\node at ({(i + .5) * W:.2f},0.35) {{{a.first + i}}};")
    out.append(f"\\node[anchor=east] at ({LBL},0.35) {{\\normalfont cycle}};")
    for i in range(n + 1):
        out.append(f"\\draw[gray!40] ({i * W:.2f},0.15) -- ({i * W:.2f},{-H * len(ROWS):.2f});")

    def box(x0, x1, y, text, fill):
        out.append(f"\\draw[fill={fill}] ({x0 + .03:.2f},{y - .2:.2f}) -- ({x0 + .1:.2f},{y + .2:.2f}) -- "
                   f"({x1 - .1:.2f},{y + .2:.2f}) -- ({x1 - .03:.2f},{y - .2:.2f}) -- cycle;")
        out.append(f"\\node[font=\\tiny\\ttfamily] at ({(x0 + x1) / 2:.2f},{y:.2f}) {{{text}}};")

    for r, (label, key) in enumerate(ROWS):
        y = -(r + 0.5) * H
        out.append(f"\\node[anchor=east] at ({LBL},{y:.2f}) {{{label}}};")
        for i in range(n):
            x0, x1 = i * W, (i + 1) * W
            d_op = s["d_re"][i] or s["d_we"][i]
            if key in ("i_ready", "d_ready", "wb_valid"):
                iv = s[key][i]
                if key == "d_ready" and not d_op:
                    out.append(f"\\fill[gray!10] ({x0:.2f},{y - .17:.2f}) rectangle ({x1:.2f},{y + .17:.2f});")
                    continue
                yy = y + (0.17 if iv else -0.17)
                out.append(f"\\draw[thick] ({x0:.2f},{yy:.2f}) -- ({x1:.2f},{yy:.2f});")
                if i and s[key][i - 1] != iv:
                    out.append(f"\\draw[thick] ({x0:.2f},{y - .17:.2f}) -- ({x0:.2f},{y + .17:.2f});")
                if not iv and key != "wb_valid":
                    out.append(f"\\fill[red!20] ({x0:.2f},{y - .17:.2f}) rectangle ({x1:.2f},{y + .17:.2f});")
                if iv and key == "wb_valid":
                    out.append(f"\\fill[violet!15] ({x0:.2f},{y - .17:.2f}) rectangle ({x1:.2f},{y + .17:.2f});")
            elif key == "pc":
                box(x0, x1, y, f"{s['pc'][i]:02x}", "white" if s["i_ready"][i] else "red!20")
            elif key == "d_addr":
                if d_op:
                    kind = "LW" if s["d_re"][i] else "SW"
                    both = s["i_ready"][i] and s["d_ready"][i]
                    box(x0, x1, y, f"{kind}~{s['d_addr'][i]:02x}", "green!25" if both else "red!20")
                else:
                    box(x0, x1, y, "--", "gray!10")
            elif key == "owner":
                if not s["m_req"][i]:
                    box(x0, x1, y, "idle", "gray!10")
                elif s["sel_d"][i]:
                    box(x0, x1, y, "D wr" if s["m_we"][i] else "D fill", "orange!30")
                else:
                    box(x0, x1, y, "I fill", "blue!20")
            elif key == "m_addr":
                if s["m_req"][i]:
                    box(x0, x1, y, f"{s['m_addr'][i]:03x}", "white")
                else:
                    box(x0, x1, y, "--", "gray!10")
    out.append("\\end{tikzpicture}")
    with open(a.out, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {a.out}: {n} cycles from {a.vcd}")


if __name__ == "__main__":
    main()
